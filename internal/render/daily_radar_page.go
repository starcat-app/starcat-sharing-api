// 本文件将日报 Markdown 限制为安全的静态 HTML，公开访问无需 JavaScript 或 cookie。
package render

import (
	"bytes"
	"html/template"
	"net/url"
	"strings"

	"github.com/starcat-app/starcat-sharing-api/internal/model"
	"github.com/yuin/goldmark"
	"github.com/yuin/goldmark/extension"
	"github.com/yuin/goldmark/parser"
	"golang.org/x/net/html"
	"golang.org/x/net/html/atom"
)

// DailyRadarPage 是模板的唯一输入；快照文本仍由 html/template 正常转义。
type DailyRadarPage struct {
	Report      model.DailyRadarReport
	Projects    []DailyRadarProjectPage
	Sources     []DailyRadarSourcePage
	Article     template.HTML
	HeroWebPURL string
	HeroPNGURL  string
	PublicURL   string
	Labels      DailyRadarLabels
}

// DailyRadarProjectPage 在安全校验后补齐唯一 GitHub 地址和头像占位字母。
type DailyRadarProjectPage struct {
	model.DailyRadarProject
	URL     string
	Avatar  string
	Initial string
}

// DailyRadarSourcePage 提供可见域名，让读者在跳转前判断来源。
type DailyRadarSourcePage struct {
	Title  string
	URL    string
	Domain string
}

// DailyRadarLabels 跟随报告内容语言，不根据访问者身份生成不同页面。
type DailyRadarLabels struct {
	Section, Projects, Sources, ReadingTime, Footer, Download, Cover string
}

// DailyRadarSafeURL 将外链统一升级到 HTTPS；拒绝凭据、相对路径和危险 scheme。
func DailyRadarSafeURL(value string) string {
	parsed, err := url.Parse(strings.TrimSpace(value))
	if err != nil || parsed.Host == "" || parsed.User != nil ||
		(parsed.Scheme != "http" && parsed.Scheme != "https") {
		return ""
	}
	parsed.Scheme = "https"
	return parsed.String()
}

// NewDailyRadarPage 只使用入库的不可变快照，不访问 GitHub 或用户数据。
func NewDailyRadarPage(share *model.DailyRadarShare, baseURL string) (DailyRadarPage, error) {
	report := share.Request.Report
	pageURL := strings.TrimRight(baseURL, "/") + "/d/" + share.ID
	page := DailyRadarPage{
		Report: report, PublicURL: pageURL, HeroWebPURL: pageURL + "/hero.webp",
		HeroPNGURL: pageURL + "/hero.png",
		Labels: DailyRadarLabels{
			Section: "Daily Radar", Projects: "Related projects", Sources: "Sources",
			ReadingTime: "min read", Footer: "Find your way back to what matters.",
			Download: "Discover Starcat", Cover: "Daily Radar report cover",
		},
	}
	if strings.HasPrefix(strings.ToLower(report.Language), "zh") {
		page.Labels = DailyRadarLabels{
			Section: "每日热点", Projects: "相关项目", Sources: "内容来源",
			ReadingTime: "分钟阅读", Footer: "让每一次收藏，都更容易找回。",
			Download: "了解 Starcat", Cover: "每日热点报告封面",
		}
	}
	for _, project := range share.Request.Projects {
		initial := strings.ToUpper(string([]rune(project.Owner)[0]))
		page.Projects = append(page.Projects, DailyRadarProjectPage{
			DailyRadarProject: project, URL: "https://github.com/" + project.Owner + "/" + project.Repo,
			Avatar: DailyRadarSafeURL(project.AvatarURL), Initial: initial,
		})
	}
	for _, source := range report.Sources {
		safe := DailyRadarSafeURL(source.URL)
		parsed, _ := url.Parse(safe)
		page.Sources = append(page.Sources, DailyRadarSourcePage{
			Title: source.Title, URL: safe, Domain: parsed.Hostname(),
		})
	}
	article, err := safeDailyRadarMarkdown(report.Markdown)
	if err != nil {
		return DailyRadarPage{}, err
	}
	// 只有经过 Goldmark 的安全默认渲染与下方 URL 属性过滤后才允许作为 HTML 插入模板。
	page.Article = template.HTML(article)
	return page, nil
}

// safeDailyRadarMarkdown 禁止原始 HTML，并检查所有链接/图片；片内锚点保留，其余只允许 HTTPS。
func safeDailyRadarMarkdown(markdown string) (string, error) {
	engine := goldmark.New(
		goldmark.WithExtensions(extension.GFM),
		goldmark.WithParserOptions(parser.WithAutoHeadingID()),
	)
	var generated bytes.Buffer
	if err := engine.Convert([]byte(markdown), &generated); err != nil {
		return "", err
	}
	root := &html.Node{Type: html.ElementNode, Data: "div", DataAtom: atom.Div}
	nodes, err := html.ParseFragment(&generated, root)
	if err != nil {
		return "", err
	}
	var sanitize func(*html.Node)
	sanitize = func(node *html.Node) {
		if node.Type == html.ElementNode && (node.Data == "a" || node.Data == "img") {
			name := "href"
			if node.Data == "img" {
				name = "src"
			}
			for index := range node.Attr {
				if node.Attr[index].Key != name {
					continue
				}
				value := node.Attr[index].Val
				if node.Data == "a" && strings.HasPrefix(value, "#") {
					continue
				}
				node.Attr[index].Val = DailyRadarSafeURL(value)
			}
			if node.Data == "a" {
				node.Attr = append(node.Attr, html.Attribute{Key: "rel", Val: "noopener noreferrer"})
			} else {
				node.Attr = append(node.Attr, html.Attribute{Key: "loading", Val: "lazy"})
			}
		}
		for child := node.FirstChild; child != nil; child = child.NextSibling {
			sanitize(child)
		}
	}
	var result bytes.Buffer
	for _, node := range nodes {
		sanitize(node)
		if err := html.Render(&result, node); err != nil {
			return "", err
		}
	}
	return result.String(), nil
}
